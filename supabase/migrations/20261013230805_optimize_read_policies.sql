create index if not exists owner_bootstrap_user_idx on private.owner_bootstrap(user_id);
alter policy public_authors on public.authors to anon;
drop policy if exists staff_read on public.authors;
drop policy if exists authenticated_read on public.authors;
create policy authenticated_read on public.authors for select to authenticated using ((is_active and deleted_at is null) or (select private.is_staff()));
alter policy public_categories on public.categories to anon;
drop policy if exists staff_read on public.categories;
drop policy if exists authenticated_read on public.categories;
create policy authenticated_read on public.categories for select to authenticated using ((is_active and deleted_at is null) or (select private.is_staff()));
alter policy public_posts on public.posts to anon;
drop policy if exists staff_read on public.posts;
drop policy if exists authenticated_read on public.posts;
create policy authenticated_read on public.posts for select to authenticated using ((status='published' and visibility='public' and deleted_at is null and published_at<=now()) or (select private.is_staff()));
alter policy public_links on public.post_categories to anon;
drop policy if exists staff_read on public.post_categories;
drop policy if exists authenticated_read on public.post_categories;
create policy authenticated_read on public.post_categories for select to authenticated using ((exists(select 1 from public.posts p where p.id=post_id) and exists(select 1 from public.categories c where c.id=category_id)) or (select private.is_staff()));
alter policy public_settings on public.site_settings to anon;
drop policy if exists staff_read on public.site_settings;
drop policy if exists authenticated_read on public.site_settings;
create policy authenticated_read on public.site_settings for select to authenticated using ((is_public) or (select private.is_staff()));
alter policy public_ticker on public.ticker_items to anon;
drop policy if exists staff_read on public.ticker_items;
drop policy if exists authenticated_read on public.ticker_items;
create policy authenticated_read on public.ticker_items for select to authenticated using ((is_active and starts_at<=now() and (ends_at is null or ends_at>now())) or (select private.is_staff()));
